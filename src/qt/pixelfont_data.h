// The glyph for a character (lower case folds to upper); '?' for anything we don't have.
inline const Glyph &glyphFor(char c)
{
    const char u = char(std::toupper(static_cast<unsigned char>(c)));
    const Glyph *question = nullptr;
    for (const Glyph &g : kGlyphs) {
        if (g.ch == u) return g;
        if (g.ch == '?') question = &g;
    }
    return *question;
}

